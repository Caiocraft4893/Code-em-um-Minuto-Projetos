'''
Faça um programa que receba a idade do usuário e diga se
ele já pode tirar a habilitação ou não!
'''

n1 = int(input('Qual sua idade: '))
if(n1 >= 18):
    print('Você possui idade para tirar a habilitação!')
else:
    print('Você ainda não possui idade para tirar a habilitação!')
